"""File classification: language detection, generated-code and test detection."""

from __future__ import annotations

import fnmatch
import re
from collections.abc import Sequence
from pathlib import PurePosixPath

from code_rag.domain.value_objects import Language

_EXT_TO_LANG: dict[str, Language] = {
    ".py": Language.PYTHON,
    ".pyi": Language.PYTHON,
    ".ts": Language.TYPESCRIPT,
    ".mts": Language.TYPESCRIPT,
    ".cts": Language.TYPESCRIPT,
    ".tsx": Language.TSX,
    ".go": Language.GO,
    ".rs": Language.RUST,
}

DEFAULT_GENERATED_GLOBS: tuple[str, ...] = (
    "*_pb2.py",
    "*_pb2_grpc.py",
    "*_pb2.pyi",
    "*.pb.go",
    "*_grpc.pb.go",
    "*.pb.gw.go",
    "*_pb.ts",
    "*_pb.d.ts",
    "*_grpc_pb.ts",
    "*.generated.*",
    "*.gen.go",
    "*.gen.ts",
    "zz_generated*.go",
    "**/generated/**",
    "**/__generated__/**",
    "**/gen/proto/**",
)

DEFAULT_EXCLUDE_GLOBS: tuple[str, ...] = (
    "**/node_modules/**",
    "**/vendor/**",
    "**/.venv/**",
    "**/venv/**",
    "**/dist/**",
    "**/build/**",
    "**/target/**",
    "**/.git/**",
    "*.min.js",
    "*.d.ts",
)

_GENERATED_HEADER = re.compile(
    r"(code generated .* do not edit|@generated|autogenerated|auto-generated|"
    r"generated by the protocol buffer compiler|do not edit this file)",
    re.IGNORECASE,
)

_TEST_PATTERNS: tuple[str, ...] = (
    "test_*.py",
    "*_test.py",
    "*_test.go",
    "*.test.ts",
    "*.spec.ts",
    "*.test.tsx",
    "*.spec.tsx",
    "**/tests/**",
    "**/test/**",
    "**/__tests__/**",
    "conftest.py",
)


def _match_any(path: str, globs: Sequence[str]) -> bool:
    name = PurePosixPath(path).name
    for g in globs:
        if "/" in g:
            # '**/x/**' should also match paths that start with 'x/'
            if fnmatch.fnmatch(path, g) or fnmatch.fnmatch("/" + path, g):
                return True
        elif fnmatch.fnmatch(name, g):
            return True
    return False


def detect_language(path: str) -> Language | None:
    suffix = PurePosixPath(path).suffix.lower()
    if path.endswith(".d.ts"):
        return None
    return _EXT_TO_LANG.get(suffix)


def is_proto(path: str) -> bool:
    return path.endswith(".proto")


def is_excluded(path: str, extra: Sequence[str] = ()) -> bool:
    return _match_any(path, (*DEFAULT_EXCLUDE_GLOBS, *extra))


def is_generated(path: str, head: str, extra_globs: Sequence[str] = ()) -> bool:
    if _match_any(path, (*DEFAULT_GENERATED_GLOBS, *extra_globs)):
        return True
    first_lines = "\n".join(head.splitlines()[:8])
    return bool(_GENERATED_HEADER.search(first_lines))


def is_test(path: str) -> bool:
    return _match_any(path, _TEST_PATTERNS)


def looks_binary(content: bytes) -> bool:
    return b"\x00" in content[:8192]
